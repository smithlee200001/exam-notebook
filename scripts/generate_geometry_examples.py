"""Generate editable geometry JSON demo blocks; no network or raster images."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def geometry(text, points, segments, labels, right_angles=(), circles=(), polygons=(), givens=()):
    return dict(type='geometry', text=text, version=1, coordinateSystem='screen', display={'widthPercent':60},
                viewBox=[0, 0, 900, 500],
                points={name: dict(x=x, y=y, label=name, dx=dx, dy=dy)
                        for name, (x, y, dx, dy) in points.items()},
                segments=[dict(id=a+b, **{'from': a}, to=b, dashed=dashed)
                          for a, b, dashed in segments],
                circles=list(circles), polygons=list(polygons),
                labels=[dict(x=x, y=y, text=text) for x, y, text in labels],
                rightAngles=[dict(vertex=v, arms=arms, size=22) for v, arms in right_angles],
                givens=list(givens))


def question(number, tags, blocks, parts):
    return dict(source_number=str(number), subject='数学', kind='解答题', tags=tags,
                blocks=blocks, choices=[], parts=parts, warnings=[])


def main():
    triangle = geometry('直角三角形ABC，AB长8厘米，AC长6厘米。',
        {'A': (240,390,-33,35), 'B': (640,390,10,30), 'C': (240,90,-30,-15)},
        [('A','B',False), ('A','C',False), ('B','C',False)],
        [(420,440,'8 cm'), (140,250,'6 cm'), (460,235,'x cm')],
        [('A',['B','C'])], givens=[
            dict(type='length',segment='AB',value=8,unit='cm'),
            dict(type='length',segment='AC',value=6,unit='cm'),
            dict(type='perpendicular',segments=['AB','AC'])])
    circle = geometry('圆O中AB是直径，C在上半圆，OC是辅助半径。',
        {'A': (280,250,-35,25), 'B': (620,250,15,20), 'C': (508.14,90.25,2,-25), 'O': (450,250,-10,40)},
        [('A','B',False), ('A','C',False), ('B','C',False), ('O','C',True)],
        [(345,238,'35°')], circles=[dict(id='circleO',center='O',radius=170,dashed=False)])
    rectangle = geometry('矩形ABCD，AB长8厘米，BC长6厘米，三角形ABC为阴影。',
        {'A': (250,385,-35,35), 'B': (610,385,10,35), 'C': (610,115,10,-15), 'D': (250,115,-35,-15)},
        [('A','B',False), ('B','C',False), ('C','D',False), ('D','A',False), ('A','C',False)],
        [(400,440,'8 cm'), (630,255,'6 cm')],
        [('A',['B','D']), ('B',['A','C']), ('C',['B','D']), ('D',['A','C'])],
        polygons=[dict(points=['A','B','C'],fill='shade')], givens=[
            dict(type='length',segment='AB',value=8,unit='cm'),
            dict(type='length',segment='BC',value=6,unit='cm')])

    questions = [
        question(1, ['勾股定理', '三角形面积'], [
            dict(type='text', text=r'如图，在直角三角形 \(ABC\) 中，\(\angle A=90^\circ\)，\(AB=8\,\mathrm{cm}\)，\(AC=6\,\mathrm{cm}\)，设 \(BC=x\,\mathrm{cm}\)。'),
            triangle, dict(type='text', text='可使用下面的关系式列式：'),
            dict(type='latex', text=r'AB^2+AC^2=BC^2')],
            [r'（1）求斜边 \(BC\) 的长度，写出计算过程。', r'（2）求 \(\triangle ABC\) 的面积。']),
        question(2, ['圆周角', '直径所对的圆周角', '圆心角'], [
            dict(type='text', text=r'如图，\(AB\) 是圆 \(O\) 的直径，点 \(C\) 在圆上，且 \(\angle CAB=35^\circ\)。连接 \(OC\)。'),
            circle, dict(type='text', text='同弧所对圆心角与圆周角满足：'),
            dict(type='latex', text=r'\angle BOC=2\angle BAC')],
            [r'（1）求 \(\angle ACB\) 与 \(\angle ABC\) 的度数。', r'（2）求劣弧 \(BC\) 所对圆心角 \(\angle BOC\) 的度数。']),
        question(3, ['矩形', '面积', '勾股定理'], [
            dict(type='text', text=r'如图，矩形 \(ABCD\) 中，\(AB=8\,\mathrm{cm}\)，\(BC=6\,\mathrm{cm}\)。连接对角线 \(AC\)，阴影部分为 \(\triangle ABC\)。'),
            rectangle, dict(type='text', text='三角形面积公式：'),
            dict(type='latex', text=r'S_{\triangle}=\frac{1}{2}bh')],
            [r'（1）求阴影部分的面积，并说明它占矩形面积的几分之几。', r'（2）求对角线 \(AC\) 的长度。'])
    ]
    # Return fresh objects on each click so edits and saved flags cannot leak.
    (ROOT / 'static' / 'demo.js').write_text(
        "/* Generated by scripts/generate_geometry_examples.py; do not edit by hand. */\n"
        "'use strict';\nfunction createDemoQuestions() {\n  return " +
        json.dumps(questions, ensure_ascii=False, indent=2) + ';\n}\n', encoding='utf-8')


if __name__ == '__main__':
    main()
